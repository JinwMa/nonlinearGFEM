void BaseMaterial::getC_e_tensor(double C_e_tensor[3][3][3][3])
{    
    double lambda = u * E / ((u + 1.0) * (1.0 - 2.0 * u));
    double mu = 0.5 * E / (u + 1.0);
    double I_tensor[3][3] = {0.0};
    for (int i = 0; i < 3; i++)
    {
        I_tensor[i][i] = 1.0;
    }
    for (int i = 0; i < 3; i++)
    {
        for (int j = 0; j < 3; j++)
        {
            for (int k = 0; k < 3; k++)
            {
                for (int l = 0; l < 3; l++)
                {
                    C_e_tensor[i][j][k][l] = mu * (I_tensor[i][k] * I_tensor[j][l] + I_tensor[i][l] * I_tensor[j][k]) +
                                             lambda * I_tensor[k][l] * I_tensor[i][j];
                }
            }
        }
    }
}

